-- 앱 캘린더에서 빨간 날(공휴일) 표시용. authenticated 읽기 전용.

CREATE TABLE IF NOT EXISTS public.public_holidays (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  holiday_date date NOT NULL UNIQUE,
  name text NOT NULL,
  year int NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_public_holidays_year ON public.public_holidays(year);
CREATE INDEX IF NOT EXISTS idx_public_holidays_date ON public.public_holidays(holiday_date);

ALTER TABLE public.public_holidays ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Authenticated read public holidays" ON public.public_holidays;
CREATE POLICY "Authenticated read public holidays"
  ON public.public_holidays FOR SELECT
  TO authenticated
  USING (true);

